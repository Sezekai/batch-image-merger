const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  init: () => ipcRenderer.invoke('init'),
  save: (k, data) => ipcRenderer.invoke('save', k, data),
  pickFolders: (opts) => ipcRenderer.invoke('pickFolders', opts),
  engine: (op, args, prio) => ipcRenderer.invoke('engine', op, args, prio),
  exportOne: (job, reserved) => ipcRenderer.invoke('exportOne', job, reserved),
  cancelExport: () => ipcRenderer.invoke('cancelExport'),
  previewRender: (job, max) => ipcRenderer.invoke('previewRender', job, max),
  showItem: (p) => ipcRenderer.invoke('showItem', p),
  openPath: (p) => ipcRenderer.invoke('openPath', p),
  fullscreen: (on) => ipcRenderer.invoke('fullscreen', on),
  exists: (p) => ipcRenderer.invoke('exists', p),
  relaunch: (opts) => ipcRenderer.invoke('relaunch', opts),
  setTitleBar: (c) => ipcRenderer.invoke('setTitleBar', c),
  log: (text, kind) => ipcRenderer.send('log', text, kind),
  doing: (what) => ipcRenderer.send('doing', what),
  selftestReady: (info) => ipcRenderer.send('selftest-ready', info),
  storage: {
    list: () => ipcRenderer.invoke('storage:list'),
    size: (id) => ipcRenderer.invoke('storage:size', id),
    open: (id) => ipcRenderer.invoke('storage:open', id),
    clear: () => ipcRenderer.invoke('storage:clear'),
    retry: () => ipcRenderer.invoke('storage:retry'),
    move: (id, busy) => ipcRenderer.invoke('storage:move', id, busy),
  },
  migrateCache: () => ipcRenderer.invoke('migrateCache'),
  openLogs: () => ipcRenderer.invoke('logs:open'),
  fonts: {
    pick: () => ipcRenderer.invoke('fonts:pick'),
    install: (family, files) => ipcRenderer.invoke('fonts:install', family, files),
    list: () => ipcRenderer.invoke('fonts:list'),
    read: (id, name) => ipcRenderer.invoke('fonts:read', id, name),
    remove: (id) => ipcRenderer.invoke('fonts:remove', id),
  },
  exportTheme: (t) => ipcRenderer.invoke('theme:export', t),
  importThemes: () => ipcRenderer.invoke('theme:import'),
  pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch { return ''; } },
  onExportProgress: (fn) => ipcRenderer.on('export-progress', (e, d) => fn(d)),
  onJob: (fn) => ipcRenderer.on('job', (e, d) => fn(d)),
  onLog: (fn) => ipcRenderer.on('log', (e, d) => fn(d)),
  onWinState: (fn) => ipcRenderer.on('win-state', (e, d) => fn(d)),
  fileUrl: (p) => 'bimg://f/' + encodeURIComponent(p),
});
